student = "python programming for data science"

# Print the complete string
print(student)
# Print the first character
print(student[0])
# Print the last character
print(student[-1])
# Print the first 6 characters
print(student[0:6])
# Print the last 7 characters
print(student[-7:])
# Reverse the string using slicing
print(student[::-1])
# Convert it to uppercase
print(student.upper())
# Convert it to lowercase
print(student.lower())
# Convert it to title case
print(student.title())
# Count how many times "a" appears
print(student.count("a"))
# Find the position of "programming"
print(student.find("programming"))
# Replace "data science" with "artificial intelligence"
print(student.replace("data science" , "artificial intelligence"))
# Split the string into individual words
print(student.split())