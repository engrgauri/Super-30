numbers = [10, 20, 30, 20, 40, 10, 50, 30, 60]

# Print the original list
print(numbers)
# Convert the list into a set
nums = set(numbers)
# Observe which duplicates disappear
print(nums)
# Convert the set back into a list
print(list(nums))
# Print the number of original elements
print(len(numbers))
# Print the number of unique elements
print(len(nums))
